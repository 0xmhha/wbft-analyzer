// Command gen writes internal/privacy/data/requirements.txt from the spec/
// directory of a wbft-spec checkout at the commit of spec.lock.
//
// Usage: go run ./internal/privacy/gen -spec DIR -commit COMMIT > internal/privacy/data/requirements.txt
package main

import (
	"flag"
	"fmt"
	"os"

	"github.com/0xmhha/wbft-analyzer/internal/privacy"
)

func main() {
	spec := flag.String("spec", "", "the spec/ directory of a wbft-spec checkout")
	commit := flag.String("commit", "", "the wbft-spec commit of the checkout")
	flag.Parse()
	if *spec == "" || *commit == "" {
		flag.Usage()
		os.Exit(64)
	}
	ids, err := privacy.Extract(*spec)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("# The requirement IDs of the public wbft-spec specification at %s\n", *commit)
	fmt.Println("# (spec.lock), generated by internal/privacy/gen. Do not edit.")
	for _, id := range ids {
		fmt.Println(id)
	}
}
